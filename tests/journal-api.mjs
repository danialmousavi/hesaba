import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { config } from "dotenv";
import pg from "pg";

config({ path: ".env.local" });
const base = "http://localhost:3000";
const token = randomUUID().replaceAll("-", "");
const org = `c${token}a`, year = `c${token}b`, account = `c${token}c`, membership = `c${token}d`;
const email = `journal-test-${token}@example.invalid`;
const db = new pg.Client({ connectionString: process.env.DATABASE_URL });
await db.connect();
let userId;
try {
  const signup = await fetch(`${base}/api/auth/sign-up/email`, { method: "POST", headers: { "content-type": "application/json", origin: base }, body: JSON.stringify({ name: "Journal test", email, password: randomUUID() }) });
  assert.equal(signup.status, 200, await signup.clone().text());
  userId = (await signup.json()).user.id;
  const cookie = signup.headers.getSetCookie().map((item) => item.split(";")[0]).join("; ");
  await db.query('INSERT INTO "Organization" (id,name,slug,"updatedAt") VALUES ($1,$2,$1,now())', [org, "Test"]);
  await db.query('INSERT INTO "Membership" (id,"userId","organizationId",role,"updatedAt") VALUES ($1,$2,$3,$4,now())', [membership, userId, org, "ACCOUNTANT"]);
  await db.query('INSERT INTO "FiscalYear" (id,"organizationId",name,"startDate","endDate","updatedAt") VALUES ($1,$2,$3,$4,$5,now())', [year, org, "Test", "2026-01-01", "2026-12-31"]);
  await db.query('INSERT INTO "LedgerAccount" (id,"organizationId",code,name,type,"updatedAt") VALUES ($1,$2,$3,$4,$5,now())', [account, org, "100", "Test", "ASSET"]);
  const call = (method, body) => fetch(`${base}/api/journal-entries`, { method, headers: { cookie, origin: base, "content-type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const draft = { fiscalYearId: year, number: 1, date: "2026-06-01", description: "Test", lines: [{ accountId: account, debit: "99999999999999999999", credit: "0" }] };
  assert.equal((await fetch(`${base}/api/journal-entries`)).status, 401);
  assert.equal((await call("POST", { ...draft, lines: [{ ...draft.lines[0], credit: "1" }] })).status, 400);
  const created = await call("POST", draft);
  assert.equal(created.status, 201, await created.clone().text());
  const draftEntry = (await created.json()).entry;
  assert.equal(draftEntry.status, "DRAFT");
  const reportUrl = `${base}/api/reports/trial-balance?fiscalYearId=${year}`;
  assert.equal((await fetch(reportUrl)).status, 401);
  const report = await fetch(reportUrl, { headers: { cookie } });
  assert.equal(report.status, 200);
  const reportData = await report.json();
  assert.equal(reportData.rows.length, 0);
  assert.equal(reportData.totals.debit, "0");
  assert.equal((await fetch(`${base}/api/reports/trial-balance?fiscalYearId=c${token}x`, { headers: { cookie } })).status, 404);
  const post = (id, headers = { cookie, origin: base }) => fetch(`${base}/api/journal-entries/${id}/post`, { method: "POST", headers });
  const edit = (id, body, headers = { cookie, origin: base, "content-type": "application/json" }) => fetch(`${base}/api/journal-entries/${id}`, { method: "PATCH", headers, body: JSON.stringify(body) });
  const remove = (id, headers = { cookie, origin: base }) => fetch(`${base}/api/journal-entries/${id}`, { method: "DELETE", headers });
  assert.equal((await remove(draftEntry.id, { origin: base })).status, 401);
  assert.equal((await remove(draftEntry.id, { cookie, origin: "http://example.invalid" })).status, 403);
  assert.equal((await post(draftEntry.id)).status, 400);
  assert.equal((await call("POST", draft)).status, 409);
  assert.equal((await call("POST", { ...draft, number: 2, date: "2027-01-01" })).status, 400);
  assert.equal((await call("POST", { ...draft, number: 2, lines: [{ ...draft.lines[0], accountId: `c${token}x` }] })).status, 400);
  await db.query('UPDATE "LedgerAccount" SET "isActive"=false WHERE id=$1', [account]);
  assert.equal((await call("POST", { ...draft, number: 2 })).status, 400);
  await db.query('UPDATE "LedgerAccount" SET "isActive"=true WHERE id=$1', [account]);
  const list = await call("GET");
  const entries = (await list.json()).entries;
  assert.equal(entries.length, 1);
  assert.equal(entries[0].lines[0].debit, "99999999999999999999");
  const revised = { number: 1, date: "2026-07-01", description: "اصلاح‌شده", lines: [{ accountId: account, debit: "100", credit: "0" }, { accountId: account, debit: "0", credit: "100" }] };
  assert.equal((await edit(draftEntry.id, { ...revised, date: "2027-01-01" })).status, 409);
  assert.equal((await edit(draftEntry.id, revised)).status, 200);
  const afterEdit = (await (await call("GET")).json()).entries.find((entry) => entry.id === draftEntry.id);
  assert.equal(afterEdit.description, "اصلاح‌شده");
  assert.equal(afterEdit.lines.length, 2);
  assert.equal((await edit(`c${token}x`, revised)).status, 404);
  assert.equal((await edit(draftEntry.id, revised, { cookie, origin: "http://example.invalid", "content-type": "application/json" })).status, 403);
  const balanced = await call("POST", { ...draft, number: 2, lines: [draft.lines[0], { accountId: account, debit: "0", credit: "99999999999999999999" }] });
  assert.equal(balanced.status, 201, await balanced.clone().text());
  const balancedId = (await balanced.json()).entry.id;
  await db.query('UPDATE "Membership" SET role=$1 WHERE id=$2', ["VIEWER", membership]);
  assert.equal((await remove(draftEntry.id)).status, 403);
  assert.equal((await edit(draftEntry.id, revised)).status, 403);
  assert.equal((await call("POST", { ...draft, number: 3 })).status, 403);
  assert.equal((await post(balancedId)).status, 403);
  await db.query('UPDATE "Membership" SET role=$1 WHERE id=$2', ["ADMIN", membership]);
  const closeYear = () => fetch(`${base}/api/fiscal-years/${year}/close`, { method: "POST", headers: { cookie, origin: base } });
  const closeWithDrafts = await closeYear();
  assert.equal(closeWithDrafts.status, 409);
  assert.match((await closeWithDrafts.json()).error, /پیش‌نویس/);
  const storedYear = await db.query('SELECT status FROM "FiscalYear" WHERE id=$1', [year]);
  assert.equal(storedYear.rows[0].status, "OPEN");
  assert.equal((await remove(`c${token}x`)).status, 404);
  assert.equal((await post(balancedId, { origin: base })).status, 401);
  assert.equal((await post(balancedId, { cookie, origin: "http://example.invalid" })).status, 403);
  await db.query('UPDATE "LedgerAccount" SET "isActive"=false WHERE id=$1', [account]);
  assert.equal((await post(balancedId)).status, 409);
  await db.query('UPDATE "LedgerAccount" SET "isActive"=true WHERE id=$1', [account]);
  assert.equal((await remove(balancedId)).status, 200);
  assert.equal((await remove(balancedId)).status, 404);
  const remaining = await db.query('SELECT count(*)::int AS count FROM "JournalLine" WHERE "organizationId"=$1 AND "entryId"=$2', [org, balancedId]);
  assert.equal(remaining.rows[0].count, 0);
  // Successful posting requires a disposable database because posted entries
  // intentionally cannot be deleted during test cleanup.
  await db.query('UPDATE "FiscalYear" SET status=$1 WHERE id=$2', ["CLOSED", year]);
  assert.equal((await remove(draftEntry.id)).status, 409);
  assert.equal((await edit(draftEntry.id, revised)).status, 409);
  assert.equal((await call("POST", { ...draft, number: 3 })).status, 400);
  assert.equal((await post(draftEntry.id)).status, 409);
  console.log("Journal draft API checks passed.");
} finally {
  await db.query('DELETE FROM "JournalEvent" WHERE "organizationId"=$1', [org]);
  await db.query('DELETE FROM "JournalLine" WHERE "organizationId"=$1', [org]);
  await db.query('DELETE FROM "JournalEntry" WHERE "organizationId"=$1', [org]);
  await db.query('DELETE FROM "Organization" WHERE id=$1', [org]);
  if (userId) await db.query('DELETE FROM "User" WHERE id=$1 AND email=$2', [userId, email]);
  await db.end();
}
