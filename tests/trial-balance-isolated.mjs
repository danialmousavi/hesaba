    for (const [id, code] of [[debitAccount, "100"], [creditAccount, "200"]]) await db.query('INSERT INTO "LedgerAccount" (id,"organizationId",code,name,type,"updatedAt") VALUES ($1,$2,$3,$4,$5,now())', [id, org, code, code, "ASSET"]);
